    static func badge(id: String) -> Badge? { byID[id] }

    static let byID: [String: Badge] = Dictionary(all.map { ($0.id, $0) },
                                                  uniquingKeysWith: { first, _ in first })

    static func badges(in family: BadgeFamily) -> [Badge] { all.filter { $0.family == family } }

