//
//  BadgeCatalog.swift
//  Replog
//
//  The collection. Static, ordered, and the single source of truth for what exists.
//
//  Shaped by a few rules that the research on achievement systems is consistent about:
//
//  - **Ladders, not one-offs.** Most badges sit on a rung of a series with the next rung
//    visibly close. Tier and shape escalate with the number; the motif stays constant down
//    a ladder so the progression is recognisable on a grid.
//  - **Earned, not handed out.** Nothing rewards volume for its own sake, unsafe training,
//    or bodyweight loss. Nothing is ever taken away, and no copy names a lapse.
//  - **A few stay hidden.** The Curiosities family exists so the collection keeps a tail of
//    things the athlete did not know to chase.
//
//  Ids are persisted on awards, so once shipped an id never changes. Copy may.
//

